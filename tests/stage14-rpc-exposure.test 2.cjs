'use strict';
const {test}=require('node:test');const assert=require('node:assert/strict');
const {review,names}=require('../tools/stage14-review-rpc-exposure.cjs');
const good=()=>names.map(function_name=>({function_name,installed:true,schema_name:'public',anon_execute:false,public_execute:false,authenticated_execute:true,security_definer:true,search_path_safe:true}));
test('rpc evidence accepts complete candidate metadata',()=>assert.equal(review(good()).ok,true));
test('rpc evidence fails closed without rows',()=>assert.equal(review(null).ok,false));
test('rpc evidence rejects missing function',()=>assert.equal(review(good().slice(1)).ok,false));
test('rpc evidence rejects duplicate function',()=>assert.equal(review([...good(),good()[0]]).ok,false));
test('rpc evidence rejects anonymous execution',()=>{const x=good();x[0].anon_execute=true;assert.equal(review(x).ok,false)});
test('rpc evidence rejects PUBLIC execution',()=>{const x=good();x[0].public_execute=true;assert.equal(review(x).ok,false)});
test('rpc evidence rejects missing secure search path',()=>{const x=good();x[0].search_path_safe=false;assert.equal(review(x).ok,false)});
test('rpc evidence rejects unconfirmed security definer',()=>{const x=good();x[0].security_definer=null;assert.equal(review(x).ok,false)});
