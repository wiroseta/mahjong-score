'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const adapter=fs.readFileSync(path.join(root,'js/sync-supabase-adapter.js'),'utf8');
const bridge=fs.readFileSync(path.join(root,'js/sync-app-bridge.js'),'utf8');
test('production cloud release gate stays OFF',()=>assert.match(html,/const MAHJONG_CLOUD_SYNC_ENABLED=false\s*;/));
test('production bridge inherits OFF release gate',()=>assert.match(html,/MahjongCloudBridge\.create\(\{\s*enabled:MAHJONG_CLOUD_SYNC_ENABLED/));
test('application score write is gated by cloud writer permission when enabled',()=>assert.match(html,/MAHJONG_CLOUD_SYNC_ENABLED\s*&&\s*!mahjongCloudSyncBridge\.status\(\)\.canWrite/));
test('all five transfer RPC names are referenced by transport',()=>{for(const name of ['open','commit','open_reader','read','lease_status'])assert.ok(adapter.includes("'mahjong_sync_"+name+"'"),name)});
test('bridge does not persist writer tokens and monitors leases',()=>{assert.match(bridge,/startLeaseMonitor\(\)/);assert.doesNotMatch(bridge,/setItem\([^\n]*writerToken/)});
