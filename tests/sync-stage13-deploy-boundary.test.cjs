const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const rpc=fs.readFileSync('supabase_sync_rpc_draft.sql','utf8');
const unlock=fs.readFileSync('supabase_sync_admin_unlock_draft.sql','utf8');
const plan=fs.readFileSync('POSTGRES_INTEGRATION_TEST_PLAN.md','utf8');
test('unsafe RPC guard precedes transaction and any grant',()=>{const g=rpc.indexOf('UNSAFE DRAFT');assert.ok(g>=0);assert.ok(g<rpc.search(/\bBEGIN\s*;/i));assert.ok(g<rpc.search(/\bGRANT\s+EXECUTE\b/i));});
test('unsafe RPC guard is unconditional top-level exception',()=>assert.match(rpc,/DO\s+\$\$\s*BEGIN\s+RAISE\s+EXCEPTION\s+'UNSAFE DRAFT/i));
test('admin unlock draft contains no executable grant',()=>assert.doesNotMatch(unlock,/^\s*GRANT\s+EXECUTE\b/im));
test('integration gate cannot be claimed from static Node tests',()=>{assert.match(plan,/NOT EXECUTED/);assert.match(plan,/Node\.js mock or static SQL inspection does not satisfy this gate/);});
