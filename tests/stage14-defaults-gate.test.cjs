'use strict';
const {test}=require('node:test');const assert=require('node:assert/strict');
const {review,expected}=require('../tools/stage14-review-defaults.cjs');
const rows=Object.entries(expected).map(([key])=>{const [table_name,column_name]=key.split('.');return {table_name,column_name,installed:true,is_nullable:'NO',column_default:'false'};});
test('stage14 defaults accept candidate metadata',()=>assert.equal(review(rows).ok,true));
test('stage14 defaults reject absent row',()=>assert.equal(review(rows.slice(1)).ok,false));
test('stage14 defaults reject duplicate row',()=>assert.equal(review([...rows,rows[0]]).ok,false));
test('stage14 defaults reject nullable boolean',()=>assert.equal(review(rows.map((r,i)=>i?r:{...r,is_nullable:'YES'})).ok,false));
test('stage14 defaults reject true default',()=>assert.equal(review(rows.map((r,i)=>i?r:{...r,column_default:'true'})).ok,false));
test('stage14 defaults reject null default',()=>assert.equal(review(rows.map((r,i)=>i?r:{...r,column_default:null})).ok,false));
test('stage14 defaults reject untrusted expression',()=>assert.equal(review(rows.map((r,i)=>i?r:{...r,column_default:'random()'})).ok,false));
test('stage14 defaults reject malformed evidence',()=>assert.equal(review({}).ok,false));
